/**
 * Describes the direction of a mathematical range relative to a neutral
 * point, typically zero.
 */
export type Polarity = 'unipolar' | 'bipolar'

/**
 * Describes the nature of how values change across a mathematical range.
 */
export type Scale = 'linear' | 'exponential' | 'logarithmic' | 'quadratic' | 'cubic'
